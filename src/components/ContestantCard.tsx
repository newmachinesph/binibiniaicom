import Link from "next/link";
import type { Contestant } from "@/lib/types";
import { cityById } from "@/lib/cities";
import { finalScore } from "@/lib/scoring";
import { MusePortrait } from "./MusePortrait";
import { StageBadge } from "./StageBadge";
import { VoteButton } from "./VoteButton";

export function ContestantCard({ contestant, rank }: { contestant: Contestant; rank?: number }) {
  const city = cityById(contestant.cityId);
  return (
    <div className="group card overflow-hidden transition-transform duration-500 hover:-translate-y-1">
      <Link href={`/contestants/${contestant.slug}`} className="block relative">
        <div className="relative aspect-[4/5] overflow-hidden">
          <MusePortrait
            look={contestant.look}
            uid={`card-${contestant.id}`}
            name={contestant.name}
            sash={contestant.sashNumber}
            className="absolute inset-0 transition-transform duration-700 group-hover:scale-105"
          />
          <div className="absolute inset-0 bg-gradient-to-t from-ink via-ink/10 to-transparent" />

          <div className="absolute top-3 left-3 flex items-center gap-2">
            <span
              className="rounded-full bg-ink/70 backdrop-blur px-2 py-1 text-[10px] font-semibold tracking-wide text-gold-bright border border-gold/40"
              title="AI creation — every contestant is generated by AI"
            >
              AI
            </span>
            <span className="rounded-full bg-ink/70 backdrop-blur px-2 py-1 text-[11px] font-medium text-gold-bright border border-line">
              No. {contestant.sashNumber}
            </span>
            {typeof rank === "number" && (
              <span className="rounded-full bg-gradient-to-r from-gold-bright to-gold px-2 py-1 text-[11px] font-bold text-ink">
                #{rank}
              </span>
            )}
          </div>
          <div className="absolute top-3 right-3">
            <StageBadge stage={contestant.stage} />
          </div>

          <div className="absolute bottom-0 inset-x-0 p-4">
            <h3 className="font-display text-lg leading-tight">{contestant.name}</h3>
            <p className="text-xs text-mist mt-0.5">{city?.name}</p>
          </div>
        </div>
      </Link>

      <div className="flex items-center justify-between px-4 py-3 border-t border-line">
        <div>
          <p className="text-[11px] uppercase tracking-wide text-faint">Final</p>
          <p className="font-display text-xl text-gradient-gold tabular-nums leading-none">
            {finalScore(contestant.scores).toFixed(1)}
          </p>
        </div>
        <VoteButton contestantId={contestant.id} />
      </div>
    </div>
  );
}
